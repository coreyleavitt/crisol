# ---------------------------------------------------------------------------
# Version — parsed from crisol.nimble at compile time via staticRead.
# Works under both `nimble build` AND `nim r --path:src` (the project's own
# test bootstrap).  gorge/NimblePkgVersion are NOT used: gorge shells out at
# compile time and is fragile in sandboxed containers; NimblePkgVersion is only
# injected by nimble tasks, not by plain nim r.
# ---------------------------------------------------------------------------

const CrisolNimble = staticRead("../crisol.nimble")

func parseNimbleVersion(src: string): string =
  ## Extract the `version = "x.y.z"` line's value from a .nimble file.
  ## Returns "" if the line is absent or malformed.
  for line in src.splitLines():
    let s = line.strip()
    if s.startsWith("version") and s.len > 7 and s[7] in {' ', '\t', '='}:
      let eq = s.find('=')
      if eq < 0: continue
      var v = s[eq+1..^1].strip()
      if v.len >= 2 and v[0] == '"' and v[^1] == '"':
        return v[1..^2]
  return ""

const CrisolVersion* = parseNimbleVersion(CrisolNimble)

static:
  doAssert CrisolVersion.len > 0 and CrisolVersion[0] in {'0'..'9'},
    "crisol: failed to parse version from crisol.nimble — check the version = line"

