const NimGeneratedHeaderMarker* = "/* Generated by Nim Compiler"
  ## The fixed marker that opens every Nim-generated `.c` file's leading
  ## 4-line comment block (verified against real 2.2.10 output — see
  ## `tests/fixtures/golden_reuse`). Exported so tests/callers can assert
  ## against the same literal without re-guessing it.

proc stripNimGeneratedHeader(content: string): string =
  ## Drop the fixed 4-line Nim-generated comment header IF `content` starts
  ## with `NimGeneratedHeaderMarker`; otherwise return `content` unchanged
  ## (a vendor `.c` file or a `ccCmd` string never carries this marker).
  ## Bounded: exactly 4 newlines from the start — not a parser.
  if not content.startsWith(NimGeneratedHeaderMarker):
    return content
  var idx = 0
  var newlines = 0
  while idx < content.len and newlines < 4:
    if content[idx] == '\n': inc newlines
    inc idx
  result = if idx >= content.len: content else: content[idx .. ^1]

proc inlineResponseFiles(s: string; readFile: FileReaderProc): string =
  ## Replace every whitespace-delimited `@path` token with `@<contentHash>`,
  ## reading `path`'s real content through the injected seam. Every other
  ## byte (including all whitespace/newlines) is copied through unchanged —
  ## this is a surgical in-place scan, never a retokenize-and-rejoin, so it
  ## cannot reformat a multi-line `.c` file's body.
  result = newStringOfCap(s.len)
  var i = 0
  while i < s.len:
    let atTokenStart = i == 0 or s[i - 1] in {' ', '\t', '\n', '\r'}
    if s[i] == '@' and atTokenStart:
      var j = i + 1
      while j < s.len and s[j] notin {' ', '\t', '\n', '\r'}:
        inc j
      let path = s[i + 1 ..< j]
      if path.len > 0:
        let (content, ok) = readFile(path)
        let digestSrc = if ok: content else: "<unreadable:" & path & ">"
        result.add "@"
        result.add toHex16(fnv1a64(digestSrc))
      else:
        result.add s[i]
      i = j
    else:
      result.add s[i]
      inc i

proc eraseKnownString(s, known: string): string =
  ## Erase every occurrence of `known` in `s`, EXCEPT where the match is
  ## immediately followed by an identifier character (letter/digit/`_`) —
  ## a superstring-boundary guard (R14-T7 finding). A blind `s.replace(known,
  ## "")` corrupts a real project token that happens to have `known` as a
  ## PREFIX (e.g. known cacheDir `/proj/gen/ep_a_3`, real flag
  ## `-I/proj/gen/ep_a_3_vendor` — a naive replace would strip the shared
  ## prefix and leave a mangled `-I_vendor`). This stays EXACT-string
  ## matching (never a path-shape regex, per the module doc's discipline) —
  ## only a boundary check is added, and on the ambiguous case it declines to
  ## erase (leaving the known string present) rather than risk corrupting a
  ## different token: a false negative here only under-counts reuse, never
  ## falsely claims it.
  ##
  ## CAVEAT: only the TRAILING boundary is guarded (the char immediately
  ## after the match). This is sound today only because every production
  ## `knownStrings` value is an absolute (`/`-anchored) path (see callers:
  ## `nimcacheDir`/`outputBinPath.parentDir()`) — `/` is never an
  ## `IdentChars` char, so a leading identifier prefix can never fuse with
  ## an absolute-path match into one token. A future caller passing a
  ## non-`/`-anchored known string (e.g. a bare basename) could hit a
  ## leading-boundary false-erase (stripping it out of a larger identifier
  ## it's merely a suffix of). Guard both boundaries if this is ever reused
  ## outside the current absolute-path call sites.
  if known.len == 0: return s
  result = newStringOfCap(s.len)
  var i = 0
  while i < s.len:
    if i + known.len <= s.len and s[i ..< i + known.len] == known:
      let nextIdx = i + known.len
      let boundaryOk = nextIdx >= s.len or s[nextIdx] notin IdentChars
      if boundaryOk:
        i = nextIdx
        continue
    result.add s[i]
    inc i

proc normalize*(content: string; knownStrings: openArray[string];
                readFile: FileReaderProc = realFileReader): string =
  ## EXACT known-string erasure (see module doc). `knownStrings` are the
  ## exact `cacheDir`/`binDir` strings the CALLER constructed — never
  ## guessed here. Erasure is boundary-guarded against superstring
  ## corruption (see `eraseKnownString`, R14-T7).
  result = stripNimGeneratedHeader(content)
  result = inlineResponseFiles(result, readFile)
  for known in knownStrings:
    if known.len > 0:
      result = eraseKnownString(result, known)

