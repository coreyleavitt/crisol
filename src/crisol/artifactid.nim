type
  FileReaderProc* = proc(path: string): tuple[content: string; ok: bool] {.closure.}
    ## Never raises; failure (missing/unreadable file) surfaces as ok=false.

proc realFileReader*(path: string): tuple[content: string; ok: bool] =
  ## Default seam: std/os `readFile`. Never raises.
  try:
    result = (content: readFile(path), ok: true)
  except CatchableError:
    result = (content: "", ok: false)

# ---------------------------------------------------------------------------
# Internal: chainComponent — mirrors keys.chainComponent exactly (see module
# doc for why this small helper is duplicated rather than imported).
# ---------------------------------------------------------------------------

proc chainComponent(running: uint64; component: string): uint64 {.inline.} =
  let compDigest = toHex16(fnv1a64(component))
  fnv1a64(toHex16(running) & "\x00" & compDigest)

