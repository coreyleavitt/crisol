## artifactid.nim — RFC-0006 M-artifact-identity: PURE identity + ratio core
## (pass (a) of the slice — see the RFC's M-artifact-identity bullet and its
## `normalize()` sub-bullet, plus the handoff's "2 sequenced passes" note).
##
## This module is the pure identity + ratio core (pass (a)); the runner.nim
## hook, artifact-ledger emission, and measurement-mode gate it once lacked
## are now built in pass (b) (`measureworker.nim` + `runner.nim`'s
## measurement-worker wiring — see those modules). Every effectful step here
## is still an injectable seam, mirroring `ccprobe.RunProc` (cmd,args)->
## (output,ok) and `compiledriver.CompileDriver`'s closure-field idiom —
## never a bare unseamed I/O call.
##
## ## normalize() — EXACT known-string erasure, not regex/heuristic
##
## crisol *constructs* the `cacheDir`/`binDir` strings itself (`runner.nim`:
## `cachePath(ep, config, toolchainFp)` for the common case — RFC-0006
## nimcache-persistence made this STABLE per-entrypoint, dropping the old
## volatile `_<pepIdx>` (plan-position) suffix; that suffix survives only as
## a rare same-entrypoint-twice-in-plan fallback, see runner.duplicateSlugs —
## and `binPath(ep, config) & "_" & $pepIdx` for the always-per-slot binary
## dir), so normalization is a literal substring-erase of those KNOWN
## strings — never a regex that guesses which paths "look like" slot paths
## (that risks over-stripping a real project `-I`). `normalize()` runs the
## same three steps on BOTH the `.c` file's content and the `ccCmd` string
## (the caller passes whichever it has; each step is a no-op where it does
## not apply to that content's shape):
##
##   1. Strip the fixed 4-line Nim-generated header comment block — but ONLY
##      when the content actually starts with Nim's own generated-header
##      marker (`/* Generated by Nim Compiler`). A vendor `{.compile.}` `.c`
##      file (e.g. this slice's golden fixture's `fixture.c`) is NOT
##      Nim-generated and carries no such marker, so this step is a genuine
##      no-op for it — unlike a blind "chop the first 4 lines" scaffold,
##      which would corrupt a vendor file's own leading comment. A `ccCmd`
##      string never starts with the marker either, so this step is also a
##      no-op there.
##   2. Inline-hash `@response-file` arguments: cc's OWN response-file
##      syntax is an argv token beginning with a literal `@` (GCC: "@file
##      reads command-line options from file"). Detecting that token is
##      exact (checking the first byte of a whitespace-delimited token), not
##      a heuristic guess about path shapes. The referenced file's CONTENT
##      is read via the injectable `readFile` seam and folded into a short
##      digest that replaces the token in place — so a `.rsp`-only content
##      change becomes visible in the normalized string even though the
##      literal `@path` token itself does not change. Every other byte
##      (including all whitespace/newlines) is preserved untouched, so this
##      never reformats a `.c` file's body.
##   3. Erase every known `cacheDir`/`binDir` string, verbatim, in the order
##      given. These are the exact strings the CALLER constructed (never
##      re-derived or guessed here).
##
## ## ccIncludeClosure() — the FULL `cc -M` #include closure
##
## Per RFC-0006's soundness argument, `.c`-content identity alone is only an
## UPPER BOUND on safely-reusable identity: the cc also reads the module's
## full transitive `#include` closure, and a distro header backport that
## patches a struct layout without moving a version string must invalidate
## the key. `ccIncludeClosure` derives a `cc -M` (not `-MM` — system headers
## included, per the RFC's soundness argument that a libc/header upgrade
## must be visible too) invocation from the manifest's own `ccCmd`.
##
## **Review Finding 1 (soundness): REPLICATE, never allow-list.** An earlier
## version of `deriveCcMInvocation` kept only tokens starting with
## `-I`/`-D`/`-std` and dropped everything else. GCC/Clang have OTHER flags
## that change header resolution — `-isystem`, `-iquote`, `-idirafter`,
## `-include`, `-imacros`, `-iprefix`, `-nostdinc`, and more — reachable via
## a project's `--passC`. Dropping one of these means the probe searches
## DIFFERENT directories than the real compile: a header reachable ONLY via
## a dropped flag can change in place (same path text, same `.c`, same
## normalized cc command) without changing `includeClosureContentHash` —
## identical key/preimage, wrong-hit. `deriveCcMInvocation` therefore
## REPLICATES the real `ccCmd`'s arguments verbatim and only REMOVES what
## must not be there for a `-M` dependency-listing run: the compile-action
## flag `-c`, and the output flag `-o <obj>` (both the space-separated and
## fused `-o<obj>` forms). Every other flag — `-I`/`-D`/`-std`/`-isystem`/
## `-iquote`/`-include`/`-nostdinc`/anything else — survives untouched, so
## the probe resolves headers under EXACTLY the same search path the real
## compile used. Then runs the result through the injectable `RunProc` seam
## (`crisol/ccprobe`'s own (cmd,args)->(output,ok) shape — reused, not
## reinvented) and parses the Make-style dependency output into the header
## set. Each header's CONTENT (not just its path) is hashed via the
## injectable `FileReaderProc` seam, folded exactly like `depgraph.
## closureContentHash` (sorted paths, chained FNV-1a, path+content both
## mixed in) — mirrored, not reinvented.
##
## ## artifactKeyHash() — the Stage-R key material hash
##
## `normalized(ccCmd) ⊕ normalized .c content ⊕ full cc -M #include-closure
## content-hash`, using `keys.soundnessKey`'s own per-component-wrapped
## chained-FNV-1a idiom (`keys.chainComponent` is module-private to
## `keys.nim`; the 4-line helper is duplicated here rather than exported
## across an unrelated import — the same deliberate, documented choice
## `artifactledger.nim` makes for its `bootId` duplication).
##
## The RFC states Stage M must measure "on the exact key material Stage R
## would use" — Stage R's own key (removed with the object cache; see the
## RFC's §Soundness) additionally folded `nimVersion`/`ccVersion` (toolchain
## fingerprint, constant within one run — irrelevant to cross-entrypoint
## sharing WITHIN that run) and `normalize(ccCmd)` (a REAL per-unit flag
## delta that two entrypoints can genuinely differ on).
## Omitting `ccCmd` here let M over-count sharing: two units with identical
## `.c` + closure but a real cc-flag delta would count as SHARED under M's
## ratio while genuinely MISSING under R's key. Folding `normalizedCcCmd`
## makes M's key a true PREFIX of R's (differing only by the
## legitimately-constant-within-a-run nimVersion/ccVersion suffix) — see
## `docs/rfc/0006-cross-entrypoint-compile-reuse.md` §Soundness and the
## stage-4 review's R5 finding.
##
## `normalizedCcCmd` is the LAST parameter with a `""` default — not the
## first, despite being folded FIRST internally — so existing 2-arg call
## sites (the committed golden-fixture oracle test, which pins closed-form
## r_size/r_time numbers over a FIXED, uniform per-run cc command and so is
## insensitive to which constant gets folded in, as long as it's the SAME
## constant for every call in that file) keep compiling and computing
## unchanged. The production caller (`measureworker.recordArtifactRows`)
## passes the real normalized cc command explicitly.
##
## ## reuseRatios() — r_time (PRIMARY) and r_size (secondary)
##
## Pure, over `ArtifactRecord`s mirroring `artifactledger.ArtifactRow`'s
## field shape. A unit is "shared" iff its `keyHash` is carried by ≥2
## DISTINCT entrypoints within its (`groupId`,`configHash`) segment.
## `r_time = sharedCcTime / totalCcTime` (cc-time-weighted, the decision
## gate's PRIMARY metric — RFC-0006 Motivation's "wrong weighting answers
## the wrong question" trap); `r_size` is the size-weighted secondary,
## storage-planning analog. Segmented by group/config, mirroring M-report's
## segmentation.

