type
  ArtifactRecord* = object
    ## One per-entrypoint reusable-unit observation — mirrors
    ## `artifactledger.ArtifactRow`'s field shape (this module does not
    ## import/depend on that module; the shape is mirrored deliberately so
    ## a future pass (b) writer can construct one directly from the other).
    entrypointIdentity*: string  ## distinguishes WHICH entrypoint carries this unit
    groupId*:            string  ## segmentation
    configHash*:         string  ## segmentation
    basename*:           string  ## generated .c basename
    keyHash*:            string  ## artifactKeyHash() output (or any opaque key)
    sizeBytes*:          int64
    ccTimeUs*:           int64

  ReuseSegmentKey* = tuple[groupId, configHash: string]

  ReuseRatios* = object
    rTime*:          float   ## PRIMARY: cc-time-weighted reuse ratio
    rSize*:          float   ## secondary: size-weighted reuse ratio
    totalCcTimeUs*:  int64
    sharedCcTimeUs*: int64
    totalBytes*:     int64
    sharedBytes*:    int64

proc reuseRatios*(records: seq[ArtifactRecord]): Table[ReuseSegmentKey, ReuseRatios] =
  ## Compute `r_time` (PRIMARY) and `r_size` (secondary) per (`groupId`,
  ## `configHash`) segment. A record is "shared" iff its `keyHash` is
  ## carried by ≥2 DISTINCT `entrypointIdentity` values within its own
  ## segment (deduplicated — the same entrypoint appearing twice for the
  ## same keyHash does not itself constitute sharing).
  var bySegment: Table[ReuseSegmentKey, seq[ArtifactRecord]]
  for r in records:
    let segKey: ReuseSegmentKey = (groupId: r.groupId, configHash: r.configHash)
    bySegment.mgetOrPut(segKey, newSeq[ArtifactRecord]()).add r

  for segKey, segRecords in bySegment:
    var entrypointsByKey: Table[string, HashSet[string]]
    for r in segRecords:
      entrypointsByKey.mgetOrPut(r.keyHash, initHashSet[string]()).incl r.entrypointIdentity

    var totalCc, sharedCc, totalBytes, sharedBytes: int64
    for r in segRecords:
      totalCc += r.ccTimeUs
      totalBytes += r.sizeBytes
      if entrypointsByKey[r.keyHash].len >= 2:
        sharedCc += r.ccTimeUs
        sharedBytes += r.sizeBytes

    let rTime = if totalCc == 0: 0.0 else: sharedCc.float / totalCc.float
    let rSize = if totalBytes == 0: 0.0 else: sharedBytes.float / totalBytes.float
    result[segKey] = ReuseRatios(rTime: rTime, rSize: rSize,
                                 totalCcTimeUs: totalCc, sharedCcTimeUs: sharedCc,
                                 totalBytes: totalBytes, sharedBytes: sharedBytes)
