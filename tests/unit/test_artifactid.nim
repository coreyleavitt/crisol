# Behavior 3 — ccIncludeClosure(): synthetic cc -M parsing + content hash
# ===========================================================================

suite "ccIncludeClosure — synthetic cc -M Make-output parsing + header content hash":

  proc syntheticReader(mapping: Table[string, string]): FileReaderProc =
    result = proc(path: string): tuple[content: string; ok: bool] =
      if mapping.hasKey(path):
        (content: mapping[path], ok: true)
      else:
        (content: "", ok: false)

  test "review Finding 1: deriveCcMInvocation REPLICATES the real command verbatim, dropping only -c and -o <obj>":
    ## Previously an ALLOW-LIST (kept only -I/-D/-std, silently dropped
    ## everything else, including -w and -fmax-errors=3 here). Now a
    ## DENYLIST of exactly the two things a -M run must not carry: the
    ## compile-action flag and the output flag. Every other flag —
    ## including ones this probe doesn't specifically know about — must
    ## survive verbatim (see the two new tests below for -isystem/-include,
    ## the exact class of flag the allow-list used to silently drop).
    let ccCmd = "gcc -c -w -fmax-errors=3 -I/inc -I/nim/lib -DFOO=1 -std=c99 " &
                "-o /cache/@pfoo.nim.c.o /cache/@pfoo.nim.c"
    let inv = deriveCcMInvocation(ccCmd)
    check inv.ok
    check inv.cmd == "gcc"
    check inv.sourceFile == "/cache/@pfoo.nim.c"
    check inv.args == @["-M", "-w", "-fmax-errors=3", "-I/inc", "-I/nim/lib",
                        "-DFOO=1", "-std=c99", "/cache/@pfoo.nim.c"]

  test "review Finding 1: -isystem is RETAINED (previously silently dropped by the allow-list — wrong-hit class)":
    ## -isystem changes where the compiler looks for headers exactly like -I
    ## does, just with system-header semantics; a project passing it via
    ## --passC is realistic. The pre-fix allow-list dropped it (it starts
    ## with neither -I, -D, nor -std), so the cc -M probe searched a
    ## DIFFERENT set of directories than the real compile — a header
    ## reachable only via -isystem could change in place without changing
    ## includeClosureContentHash, an undetected wrong-hit.
    let ccCmd = "gcc -c -w -isystem /vendor/inc -I/proj/inc -o /cache/mod.c.o /cache/mod.c"
    let inv = deriveCcMInvocation(ccCmd)
    check inv.ok
    check "-isystem" in inv.args
    check "/vendor/inc" in inv.args
    check inv.args == @["-M", "-w", "-isystem", "/vendor/inc", "-I/proj/inc", "/cache/mod.c"]

  test "review Finding 1: -include is RETAINED (previously silently dropped by the allow-list — wrong-hit class)":
    ## -include force-includes a header before the translation unit even
    ## starts — every bit as header-resolution-relevant as -I. Same
    ## wrong-hit exposure as -isystem above under the pre-fix allow-list.
    let ccCmd = "gcc -c -include /proj/config.h -I/proj/inc -o /cache/mod.c.o /cache/mod.c"
    let inv = deriveCcMInvocation(ccCmd)
    check inv.ok
    check "-include" in inv.args
    check "/proj/config.h" in inv.args
    check inv.args == @["-M", "-include", "/proj/config.h", "-I/proj/inc", "/cache/mod.c"]

  test "review Finding 1 regression: -c and space-separated -o <obj> are removed, -M added, source preserved, other flags verbatim":
    let ccCmd = "gcc -c -w -I/inc -o /cache/mod.c.o /cache/mod.c"
    let inv = deriveCcMInvocation(ccCmd)
    check inv.ok
    check "-c" notin inv.args
    check "-o" notin inv.args
    check "/cache/mod.c.o" notin inv.args   # the -o argument itself is gone too
    check inv.args == @["-M", "-w", "-I/inc", "/cache/mod.c"]

  test "review Finding 1 regression: the fused -o<obj> form is dropped as a single token, other flags verbatim":
    let ccCmd = "gcc -c -w -I/inc -o/cache/mod.c.o /cache/mod.c"
    let inv = deriveCcMInvocation(ccCmd)
    check inv.ok
    for a in inv.args:
      check not (a.startsWith("-o") and a.len > 2)   # no fused -o<obj> survives
    check inv.args == @["-M", "-w", "-I/inc", "/cache/mod.c"]

  test "R4: a ccCmd too short to derive a cc -M invocation degrades to ok=false, never raises":
    ## Previously `doAssert toks.len >= 2` — an AssertionDefect, a `Defect`
    ## NOT caught by `runCompileCacheWorker`'s `except CatchableError`
    ## escape hatch. A malformed/degenerate manifest entry must degrade
    ## gracefully like every other per-unit oddity in this module.
    let inv = deriveCcMInvocation("gcc")   # single token — no source file
    check not inv.ok
    check inv.cmd == ""
    check inv.args.len == 0
    check inv.sourceFile == ""

  test "R1b: a shell-quoted -I path containing a space is tokenized correctly (shell-aware, not naive splitWhitespace)":
    ## Realistic under WSL2 / a mounted toolchain with a space in its path.
    ## Nim's own cc-command construction shell-quotes such an argument
    ## (`quoteShellPosix`) before it ever reaches the shell that actually
    ## runs the compile — so deriving the cc -M invocation must tokenize the
    ## SAME way, or the -I path is corrupted into two bogus tokens and the
    ## resulting closure probe silently omits headers reachable only via
    ## that -I.
    let ccCmd = "gcc -c -w '-I/opt/my toolchain/include' -o /cache/mod.c.o /cache/mod.c"
    let inv = deriveCcMInvocation(ccCmd)
    check inv.ok
    check inv.cmd == "gcc"
    check inv.sourceFile == "/cache/mod.c"
    check "-I/opt/my toolchain/include" in inv.args
    check inv.args == @["-M", "-w", "-I/opt/my toolchain/include", "/cache/mod.c"]

  test "R1b: an unterminated shell quote is fail-safe (ok=false), never mis-tokenizes and never raises":
    let ccCmd = "gcc -c -w '-I/opt/unterminated -o /cache/mod.c.o /cache/mod.c"
    let inv = deriveCcMInvocation(ccCmd)
    check not inv.ok

  test "parses a Make-style dependency list (with backslash continuations) into the header set":
    let ccMOutput = "@pfoo.nim.c.o: /cache/@pfoo.nim.c \\\n" &
                    " /inc/foo.h \\\n" &
                    " /usr/include/stdio.h\n"
    let headers = ccIncludeHeaders(ccMOutput, "/cache/@pfoo.nim.c")
    check headers.len == 2
    check "/inc/foo.h" in headers
    check "/usr/include/stdio.h" in headers
    check "/cache/@pfoo.nim.c" notin headers   # source itself excluded

  test "ccIncludeClosure via an injected synthetic run seam returns headers + a content hash":
    let ccCmd = "gcc -c -I/inc -o out.o /src/mod.c"
    let ccMOutput = "out.o: /src/mod.c /inc/foo.h\n"
    let run: RunProc = proc(cmd: string, args: openArray[string]): tuple[output: string, ok: bool] =
      check cmd == "gcc"
      (output: ccMOutput, ok: true)
    let reader = syntheticReader({"/inc/foo.h": "int x;"}.toTable)
    let res = ccIncludeClosure(ccCmd, run, reader)
    check res.ok
    check res.headers == @["/inc/foo.h"]
    check res.contentHash.len > 0

  test "a header's CONTENT change (backport, no path/version change) changes the closure hash":
    let ccCmd = "gcc -c -I/inc -o out.o /src/mod.c"
    let ccMOutput = "out.o: /src/mod.c /inc/foo.h\n"
    let run: RunProc = proc(cmd: string, args: openArray[string]): tuple[output: string, ok: bool] =
      (output: ccMOutput, ok: true)
    let readerOld = syntheticReader({"/inc/foo.h": "struct S { int a; };"}.toTable)
    let readerNew = syntheticReader({"/inc/foo.h": "struct S { int a; int b; };"}.toTable)
    let resOld = ccIncludeClosure(ccCmd, run, readerOld)
    let resNew = ccIncludeClosure(ccCmd, run, readerNew)
    check resOld.contentHash != resNew.contentHash

  test "a failed cc -M invocation surfaces ok=false, never raises":
    let ccCmd = "gcc -c -I/inc -o out.o /src/mod.c"
    let run: RunProc = proc(cmd: string, args: openArray[string]): tuple[output: string, ok: bool] =
      (output: "", ok: false)
    let res = ccIncludeClosure(ccCmd, run, realFileReader)
    check not res.ok
    check res.headers.len == 0

  test "R1b/R4: an undeivable cc -M invocation (too short / unterminated quote) surfaces ok=false, never raises, and never even calls run":
    var runCalled = false
    let run: RunProc = proc(cmd: string, args: openArray[string]): tuple[output: string, ok: bool] =
      runCalled = true
      (output: "should never be reached", ok: true)
    let res = ccIncludeClosure("gcc", run, realFileReader)   # too short — no source file
    check not res.ok
    check res.headers.len == 0
    check res.contentHash == ""
    check not runCalled

  test "includeClosureContentHash is order-independent (same set, different input order)":
    let reader = syntheticReader({"/a.h": "AAA", "/b.h": "BBB"}.toTable)
    check includeClosureContentHash(@["/a.h", "/b.h"], reader) ==
          includeClosureContentHash(@["/b.h", "/a.h"], reader)

