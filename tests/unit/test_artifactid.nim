suite "normalize — @response-file content inlining":

  proc syntheticReader(mapping: Table[string, string]): FileReaderProc =
    result = proc(path: string): tuple[content: string; ok: bool] =
      if mapping.hasKey(path):
        (content: mapping[path], ok: true)
      else:
        (content: "", ok: false)

  test "a bare ccCmd with no @token is untouched":
    let ccCmd = "gcc -c -w -I/inc -o out.o in.c"
    let reader = syntheticReader(initTable[string, string]())
    check normalize(ccCmd, @[], reader) == ccCmd

  test "an @response-file token is replaced by a hash of its REFERENCED content":
    let ccCmd = "gcc -c @/tmp/args.rsp -o out.o in.c"
    let reader = syntheticReader({"/tmp/args.rsp": "-DFOO=1 -DBAR=2"}.toTable)
    let normalized = normalize(ccCmd, @[], reader)
    check "@/tmp/args.rsp" notin normalized   # literal path token is gone
    check "-o out.o in.c" in normalized       # everything else preserved verbatim

  test "identical response-file CONTENT (even at different paths) yields the SAME inlined digest":
    let cmdA = "gcc @/tmp/a.rsp -o out.o in.c"
    let cmdB = "gcc @/tmp/b.rsp -o out.o in.c"
    let reader = syntheticReader({"/tmp/a.rsp": "-DFOO=1", "/tmp/b.rsp": "-DFOO=1"}.toTable)
    check normalize(cmdA, @[], reader) == normalize(cmdB, @[], reader)

  test "a .rsp-only CONTENT change changes the normalized result even though the ccCmd string (sans content) is otherwise identical":
    let ccCmd = "gcc @/tmp/args.rsp -o out.o in.c"
    let readerV1 = syntheticReader({"/tmp/args.rsp": "-DFOO=1"}.toTable)
    let readerV2 = syntheticReader({"/tmp/args.rsp": "-DFOO=2"}.toTable)
    check normalize(ccCmd, @[], readerV1) != normalize(ccCmd, @[], readerV2)

  test "an unreadable response file degrades to a distinct sentinel-derived digest rather than raising":
    let ccCmd = "gcc @/tmp/missing.rsp -o out.o in.c"
    let reader = syntheticReader(initTable[string, string]())
    let normalized = normalize(ccCmd, @[], reader)
    check "@/tmp/missing.rsp" notin normalized
    check normalized.len > 0

