suite "reuseRatios — closed-form r_time (primary) / r_size (secondary), segmented":

  test "two entrypoints sharing one unit and diverging on another: r_time and r_size computed correctly":
    let records = @[
      ArtifactRecord(entrypointIdentity: "ep_a", groupId: "g", configHash: "c",
                     basename: "shared.c", keyHash: "K_SHARED", sizeBytes: 100, ccTimeUs: 50),
      ArtifactRecord(entrypointIdentity: "ep_b", groupId: "g", configHash: "c",
                     basename: "shared.c", keyHash: "K_SHARED", sizeBytes: 100, ccTimeUs: 50),
      ArtifactRecord(entrypointIdentity: "ep_a", groupId: "g", configHash: "c",
                     basename: "tailored.c", keyHash: "K_TAILORED_A", sizeBytes: 20, ccTimeUs: 200),
      ArtifactRecord(entrypointIdentity: "ep_b", groupId: "g", configHash: "c",
                     basename: "tailored.c", keyHash: "K_TAILORED_B", sizeBytes: 20, ccTimeUs: 200),
    ]
    let ratios = reuseRatios(records)
    check ratios.len == 1
    let r = ratios[(groupId: "g", configHash: "c")]
    # bytes: shared=200 (100*2), total=240 (200+40) -> r_size = 200/240
    check abs(r.rSize - (200.0 / 240.0)) < 1e-9
    # cc time: shared=100 (50*2), total=500 (100+400) -> r_time = 100/500 = 0.2
    check abs(r.rTime - 0.2) < 1e-9
    check r.rTime != r.rSize   # the exact divergence RFC-0006 names

  test "a keyHash carried by only ONE entrypoint (no cross-entrypoint sharing) contributes nothing to the shared numerator":
    let records = @[
      ArtifactRecord(entrypointIdentity: "ep_a", groupId: "g", configHash: "c",
                     basename: "solo.c", keyHash: "K_SOLO", sizeBytes: 10, ccTimeUs: 10),
    ]
    let r = reuseRatios(records)[(groupId: "g", configHash: "c")]
    check r.rTime == 0.0
    check r.rSize == 0.0

  test "the same entrypoint appearing twice under the same keyHash does NOT count as cross-entrypoint sharing":
    let records = @[
      ArtifactRecord(entrypointIdentity: "ep_a", groupId: "g", configHash: "c",
                     basename: "x.c", keyHash: "K", sizeBytes: 10, ccTimeUs: 10),
      ArtifactRecord(entrypointIdentity: "ep_a", groupId: "g", configHash: "c",
                     basename: "x.c", keyHash: "K", sizeBytes: 10, ccTimeUs: 10),
    ]
    let r = reuseRatios(records)[(groupId: "g", configHash: "c")]
    check r.rTime == 0.0
    check r.rSize == 0.0

  test "segmentation: two different (groupId, configHash) segments are computed independently":
    let records = @[
      # segment (g1, c1): fully shared
      ArtifactRecord(entrypointIdentity: "ep_a", groupId: "g1", configHash: "c1",
                     basename: "u.c", keyHash: "K1", sizeBytes: 100, ccTimeUs: 100),
      ArtifactRecord(entrypointIdentity: "ep_b", groupId: "g1", configHash: "c1",
                     basename: "u.c", keyHash: "K1", sizeBytes: 100, ccTimeUs: 100),
      # segment (g2, c2): fully unshared (distinct keyHash per entrypoint)
      ArtifactRecord(entrypointIdentity: "ep_a", groupId: "g2", configHash: "c2",
                     basename: "u.c", keyHash: "K2A", sizeBytes: 100, ccTimeUs: 100),
      ArtifactRecord(entrypointIdentity: "ep_b", groupId: "g2", configHash: "c2",
                     basename: "u.c", keyHash: "K2B", sizeBytes: 100, ccTimeUs: 100),
    ]
    let ratios = reuseRatios(records)
    check ratios.len == 2
    check ratios[(groupId: "g1", configHash: "c1")].rTime == 1.0
    check ratios[(groupId: "g2", configHash: "c2")].rTime == 0.0

  test "an empty record set yields an empty segment table":
    check reuseRatios(@[]).len == 0

