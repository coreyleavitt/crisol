# Behavior 4 — artifactKeyHash(): normalized-.c ⊕ closure hash
# ===========================================================================

suite "artifactKeyHash — normalized .c content XOR'd (chained) with the closure hash":

  test "identical inputs produce identical keys":
    check artifactKeyHash("same content", "same-closure-hash") ==
          artifactKeyHash("same content", "same-closure-hash")

  test "a tailored .c body (post-normalize) changes the key even with the same closure hash":
    check artifactKeyHash("body A", "closure-x") != artifactKeyHash("body B", "closure-x")

  test "a changed closure hash changes the key even with the same .c body":
    check artifactKeyHash("same body", "closure-x") != artifactKeyHash("same body", "closure-y")

  test "the two components are not simply concatenated/commutative — swapping them changes the key":
    # (a deliberately weak but real sanity check that both components matter)
    check artifactKeyHash("X", "Y") != artifactKeyHash("Y", "X")

  test "R5: two units identical .c + closure but a DIFFERENT normalized cc command produce DIFFERENT artifactKeyHash":
    ## Stage-R's `stageRKey` folds `normalize(ccCmd)` into its key; Stage-M's
    ## `artifactKeyHash` must fold the SAME so M's key is a true PREFIX of
    ## R's — otherwise M can count two units as "shared" (same .c + closure)
    ## that would genuinely MISS under R (different cc flags), over-counting
    ## the measured r_time gate number.
    let k1 = artifactKeyHash("same body", "same-closure", "gcc -O2 -c -o a.o a.c")
    let k2 = artifactKeyHash("same body", "same-closure", "gcc -O3 -c -o a.o a.c")
    check k1 != k2

  test "R5: omitting the cc-command argument (2-arg call) is backward-compatible with a call that explicitly passes an empty string":
    ## Existing 2-arg call sites (e.g. the committed golden-fixture oracle)
    ## must keep compiling and computing consistently: the third parameter
    ## defaults to "", so a 2-arg call is exactly equivalent to explicitly
    ## folding an empty cc-command component.
    check artifactKeyHash("body", "closure") == artifactKeyHash("body", "closure", "")

