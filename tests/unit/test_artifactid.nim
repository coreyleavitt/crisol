# ===========================================================================
# Behavior 1 — normalize(): 4-line header strip + known-string erasure
# ===========================================================================

suite "normalize — Nim-generated header strip + known cacheDir/binDir erasure":

  test "strips the fixed 4-line Nim-generated header when the marker is present":
    let content = "/* Generated by Nim Compiler v2.2.10 */\n" &
                  "/* Compiled for: Linux, amd64, gcc */\n" &
                  "/* Command for C compiler:\n" &
                  "   gcc -c /nimcache_slot7/@mfoo.nim.c */\n" &
                  "#define NIM_INTBITS 64\n" &
                  "N_LIB_PRIVATE void foo(void) {}\n"
    let normalized = normalize(content, @[])
    check normalized == "#define NIM_INTBITS 64\nN_LIB_PRIVATE void foo(void) {}\n"

  test "does NOT strip a vendor .c file's own leading comment (no Nim marker present)":
    let vendor = "/* fixture.c — companion C source, not Nim-generated */\n" &
                 "#include \"fixture.h\"\n" &
                 "int crisol_fixture_double(int x) { return x * 2; }\n"
    check normalize(vendor, @[]) == vendor

  test "two real golden-shaped .c samples differing ONLY in per-slot header become byte-identical":
    proc makeUnit(cacheDir: string): string =
      "/* Generated by Nim Compiler v2.2.10 */\n" &
      "/* Compiled for: Linux, amd64, gcc */\n" &
      "/* Command for C compiler:\n" &
      "   gcc -c -w -I/opt/nim/2.2.10/lib -o " & cacheDir & "/@pfoo.nim.c.o " &
        cacheDir & "/@pfoo.nim.c */\n" &
      "#define NIM_INTBITS 64\n" &
      "N_LIB_PRIVATE void foo(void) {}\n"
    let a = makeUnit("/workspace/generated/ep_a")
    let b = makeUnit("/workspace/generated/ep_b")
    check a != b   # sanity: the strip is doing real work, not a no-op
    check normalize(a, @["/workspace/generated/ep_a"]) ==
          normalize(b, @["/workspace/generated/ep_b"])

  test "erases known cacheDir/binDir strings from a ccCmd, preserving real flag deltas":
    let ccCmd = "gcc -c -w -I/opt/nim/2.2.10/lib -I/proj/include -DFOO=1 " &
                "-o /proj/generated/ep_a_3/@pfoo.nim.c.o /proj/generated/ep_a_3/@pfoo.nim.c"
    let normalized = normalize(ccCmd, @["/proj/generated/ep_a_3"])
    check "/proj/generated/ep_a_3" notin normalized
    check "-I/opt/nim/2.2.10/lib" in normalized     # real flag, preserved
    check "-I/proj/include" in normalized           # real project -I, preserved
    check "-DFOO=1" in normalized                   # real flag, preserved

  test "erasing a known string that does not occur is a harmless no-op":
    let content = "plain content, no matches here\n"
    check normalize(content, @["/never/present"]) == content

  test "R14-T7: a real project token that is a SUPERSTRING of a known erasure string is NOT corrupted":
    ## `normalize()`'s known-string erasure is deliberately exact-substring,
    ## not regex — but a blind substring replace still has a boundary bug: a
    ## known cacheDir "/proj/gen/ep_a_3" is also a PREFIX of a real, distinct
    ## project token "-I/proj/gen/ep_a_3_vendor". A blind `.replace` would
    ## strip the shared prefix and leave a mangled "-I_vendor" remainder.
    ## normalize() must erase ONLY exact/prefix-bounded occurrences of the
    ## known string (i.e. not followed by an identifier character), leaving
    ## the superstring token completely untouched.
    let ccCmd = "gcc -c -I/proj/gen/ep_a_3_vendor -o /proj/gen/ep_a_3/@pfoo.nim.c.o " &
                "/proj/gen/ep_a_3/@pfoo.nim.c"
    let normalized = normalize(ccCmd, @["/proj/gen/ep_a_3"])
    check "-I/proj/gen/ep_a_3_vendor" in normalized      # superstring token untouched
    check "/proj/gen/ep_a_3/@pfoo.nim.c.o" notin normalized  # exact known-dir occurrence still erased
    check "/proj/gen/ep_a_3/@pfoo.nim.c" notin normalized

